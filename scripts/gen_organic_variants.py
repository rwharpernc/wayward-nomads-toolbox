"""Builds plugin/organic_variant_data.py from SrvSurvey's `bio-criteria` files (GPL-3.0, the same license as WNTB; https://github.com/njthomson/SrvSurvey).

    python scripts/gen_organic_variants.py <folder holding the bio-criteria/*.json files>

Each file describes one genus: the color variants of a species follow either the type of the star the body orbits (`star [O]`) or a material the body's surface holds (`mats [Technetium]`), set for the
whole genus or for one species, and now and then a variant also needs a kind of body (`body [Rocky]`). Only those rules are taken; the environmental rules for the species themselves are WNTB's own
(`organic_species_data.py`). The output is a data table in WNTB's own structure; the table is the facts the game's variants follow, which SrvSurvey's author worked out, and is credited to it in
docs/ATTRIBUTIONS.md and THIRD-PARTY-NOTICES.md. Run it again, and check the changes in the game, if SrvSurvey's files change.
"""
from __future__ import annotations

import glob
import json
import os
import re
import sys
from typing import Dict, List, Optional, Tuple

Entry = Tuple[str, Tuple[str, ...], Tuple[str, ...]]          # (variant, values, body kinds required)


def _terms(queries: List[str]) -> Dict[str, List[str]]:
    found: Dict[str, List[str]] = {}
    for query in queries:
        text = query.strip()
        if not text or text.startswith("#"):
            continue
        match = re.match(r"(\w+)\s*\[(.*)\]", text)
        if match:
            found[match.group(1)] = [v.strip() for v in match.group(2).split(",") if v.strip()]
    return found


def rule(children: List[dict]) -> Optional[Tuple[str, Tuple[Entry, ...]]]:
    """("star" | "mats", entries) for a list of variant children, or None when they follow neither."""
    kind = ""
    entries: List[Entry] = []
    for child in children:
        if "variant" not in child:
            continue
        terms = _terms(child.get("query", []))
        for key in ("star", "mats"):
            if key in terms:
                if kind and kind != key:
                    return None
                kind = key
                entries.append((child["variant"], tuple(terms[key]), tuple(terms.get("body", []))))
                break
        else:
            return None
    return (kind, tuple(entries)) if kind and entries else None


def species_key(genus: str, species: Optional[str]) -> str:
    name = " ".join((species or "").split())
    if not name:
        return ""
    low, g = name.casefold(), genus.casefold()
    return low if (g in low) else f"{g} {low}"


def main(folder: str) -> None:
    genus_rules: Dict[str, Tuple[str, Tuple[Entry, ...]]] = {}
    species_rules: Dict[str, Tuple[str, Tuple[Entry, ...]]] = {}
    for path in sorted(glob.glob(os.path.join(folder, "*.json"))):
        with open(path, encoding="utf-8-sig") as handle:
            data = json.load(handle)
        genus = str(data.get("genus") or os.path.splitext(os.path.basename(path))[0])
        general = rule(data.get("commonChildren", []))
        if general:
            genus_rules[genus.casefold()] = general
        for child in data.get("children", []):
            found = rule(child.get("commonChildren", []))
            own = [c for c in child.get("children", []) if "variant" in c]
            if not found and own:
                found = rule(own)                                       # variants listed straight under the species and following a material (Bacterium nebulus)
                if not found and len(own) == 1:                         # a species with one color, whatever the star or material (Stratum araneamus)
                    found = ("fixed", ((own[0]["variant"], (), ()),))
            key = species_key(genus, child.get("species"))
            if found and key:
                species_rules[key] = found
    lines = ['"""Exobiology color variants: which variant a species takes, from the type of the star its body orbits or a material the body holds.',
             "",
             "Auto-generated by scripts/gen_organic_variants.py from SrvSurvey's `bio-criteria` files (GPL-3.0, the same license as WNTB). Do not hand-edit; regenerate.",
             "See docs/ATTRIBUTIONS.md and THIRD-PARTY-NOTICES.md. Each rule is (kind, entries): kind is \"star\" (a StarType class) or \"mats\" (a surface material),",
             "and an entry is (variant, values, kinds of body it also needs, when any); kind \"fixed\" is a species with one color. A species' own rule comes before its genus's.",
             '"""',
             "",
             "from __future__ import annotations",
             "",
             "from typing import Dict, Tuple",
             "",
             "Entry = Tuple[str, Tuple[str, ...], Tuple[str, ...]]",
             "Rule = Tuple[str, Tuple[Entry, ...]]",
             "",
             "GENUS_RULES: Dict[str, Rule] = {"]
    for key in sorted(genus_rules):
        lines.append(f"    {key!r}: {genus_rules[key]!r},")
    lines += ["}", "", "SPECIES_RULES: Dict[str, Rule] = {"]
    for key in sorted(species_rules):
        lines.append(f"    {key!r}: {species_rules[key]!r},")
    lines += ["}", ""]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "plugin", "organic_variant_data.py")
    with open(out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"{len(genus_rules)} genus rules, {len(species_rules)} species rules -> {os.path.normpath(out)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
