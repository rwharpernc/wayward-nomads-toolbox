"""Ship engineering planner - pure logic (no Tk, no network): from a ship's loadout to the blueprints, grades and experimental effects it takes.

**Input.** The journal's `Loadout` event describes a ship's modules, and an engineered module carries an `Engineering` block:

    {"Slot": "FrameShiftDrive", "Item": "int_hyperdrive_size5_class5",
     "Engineering": {"BlueprintName": "FSD_LongRange", "Level": 5, "Quality": 1.0, "ExperimentalEffect": "special_fsd_heavy", ...}}

EDSY and Coriolis export a planned build in the same shape (SLEF, the Ship Loadout Exchange Format: a list of `{"header": ..., "data": <Loadout>}`), so
the commander can paste one in and see what it would take to engineer it. A single `Loadout` event copied from a journal works too.

**Mapping.** The journal names a blueprint `FSD_LongRange`; WNTB's table calls it ("Frame Shift Drive", "Increased FSD Range", grade 5). The link is
`journal_blueprints.py` (generated by scripts/gen_journal_blueprints.py), and the module type comes from the item name (`MODULE_TYPES` below).
A module this cannot place is listed as "not counted" with the reason, never guessed.

**What a plan is.** To reach level L the game applies grades 1 to L in order, so a module at level 5 takes the blueprint at grades 1, 2, 3, 4 and 5,
and the experimental effect (grade 0 in the table) is one more craft. How many rolls each grade takes depends on the game's dice, which the journal
cannot tell, so `rolls` (a number the commander sets, 1 to `MAX_ROLLS`) says how many crafts of each grade to plan for; an experimental effect is one
craft. `Plan.entries(rolls)` adds the same blueprint across modules together, ready for the wishlist (blueprint_wishlist.WishBook.add_many).

**Not counted.** Modules with no `Engineering`, which are simply left out; pre-engineered modules (the engineer id 399999 marks them), which cannot be
engineered further; and anything the mapping or the table lacks. The `Quality` of the last roll is shown but not planned with.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

from . import blueprints
from .journal_blueprints import BLUEPRINT_NAMES, SPECIAL_NAMES

MAX_TEXT_CHARS = 2_000_000
MAX_MODULES = 100
MAX_ROLLS = 10
MAX_LEVEL = 5
PRE_ENGINEERED_ID = 399999
"""The `EngineerID` the game gives a pre-engineered module (one a Frontier-made module that already carries its engineering)."""

COUNTED, PARTLY, PRE, NOT_COUNTED = "counted", "partly", "pre-engineered", "not counted"


class PlanError(ValueError):
    """The pasted text is not a ship loadout; the message says what is wrong in words the commander can act on."""


# Item name prefixes (lower case) to the module types of the blueprint table, most specific first. An item is the journal's symbol, e.g.
# "hpt_pulselaserburst_fixed_medium" or "int_hyperdrive_size5_class5"; armour is "<ship>_armour_<kind>".
MODULE_TYPES: Tuple[Tuple[str, str], ...] = (
    ("hpt_beamlaser", "Beam Laser"), ("hpt_pulselaserburst", "Burst Laser"), ("hpt_pulselaser", "Pulse Laser"), ("hpt_cannon", "Cannon"),
    ("hpt_multicannon", "Multi-cannon"), ("hpt_railgun", "Rail Gun"), ("hpt_plasmaaccelerator", "Plasma Accelerator"), ("hpt_slugshot", "Fragment Cannon"),
    ("hpt_basicmissilerack", "Missile Rack"), ("hpt_dumbfiremissilerack", "Missile Rack"), ("hpt_advancedtorppylon", "Torpedo Pylon"),
    ("hpt_minelauncher", "Mine Launcher"), ("hpt_chafflauncher", "Chaff Launcher"), ("hpt_electroniccountermeasure", "Electronic Countermeasure"),
    ("hpt_heatsinklauncher", "Heat Sink Launcher"), ("hpt_plasmapointdefence", "Point Defence"), ("hpt_shieldbooster", "Shield Booster"),
    ("hpt_cargoscanner", "Manifest Scanner"), ("hpt_crimescanner", "Kill Warrant Scanner"), ("hpt_cloudscanner", "Wake Scanner"),
    ("int_hyperdrive", "Frame Shift Drive"), ("int_engine", "Thrusters"), ("int_powerplant", "Power Plant"), ("int_powerdistributor", "Power Distributor"),
    ("int_sensors", "Sensors"), ("int_lifesupport", "Life Support"), ("int_shieldgenerator", "Shield Generator"), ("int_shieldcellbank", "Shield Cell Bank"),
    ("int_hullreinforcement", "Hull Reinforcement Package"), ("int_repairer", "Auto Field-Maintenance Unit"), ("int_fuelscoop", "Fuel Scoop"),
    ("int_fsdinterdictor", "Frame Shift Drive Interdictor"), ("int_refinery", "Refinery"), ("int_detailedsurfacescanner", "Surface Scanner"),
    ("int_dronecontrol_collection", "Collector Limpet Controller"), ("int_dronecontrol_fueltransfer", "Fuel Transfer Limpet Controller"),
    ("int_dronecontrol_prospector", "Prospector Limpet Controller"), ("int_dronecontrol_resourcesiphon", "Hatch Breaker Limpet Controller"),
)


def module_type(item: Any) -> str:
    """The table's module type for a journal item name, or "" when it is not one the table covers."""
    text = str(item or "").casefold()
    if "_armour_" in text:
        return "Armour"
    for prefix, kind in MODULE_TYPES:
        if text.startswith(prefix):
            return kind
    return ""


@dataclass(frozen=True)
class Build:
    ship: str                         # "Federation Corvette"
    name: str                         # the commander's name for the ship, or "" (shown as "Ship name (Ship)")
    modules: Tuple[Dict[str, Any], ...]

    @property
    def label(self) -> str:
        return f"{self.name} ({self.ship})" if self.name else self.ship


@dataclass(frozen=True)
class PlannedModule:
    slot: str
    item: str
    module_type: str                  # "" when the item is not one the table covers
    blueprint: str                    # the table's name, or the journal's if it could not be placed
    level: int
    experimental: str                 # the effect's name, or ""
    status: str                       # COUNTED, PARTLY, PRE or NOT_COUNTED
    note: str                         # why a module is partly or not counted, or ""
    grades: Tuple[blueprints.Blueprint, ...]
    special: Optional[blueprints.Blueprint]
    quality: float


def _words(item: Any) -> str:
    return " ".join(str(item or "").replace("_", " ").split()).title()


def parse(text: Any) -> List[Build]:
    """The ship builds in pasted text: a SLEF list, one SLEF object, or one journal `Loadout` event. Raises PlanError if there is none."""
    if not isinstance(text, str) or not text.strip():
        raise PlanError("Nothing to read. Copy a ship loadout from EDSY or Coriolis (a SLEF export) and paste it.")
    if len(text) > MAX_TEXT_CHARS:
        raise PlanError("That is too much text for a ship loadout.")
    try:
        raw = json.loads(text)
    except ValueError:
        raise PlanError("That is not JSON. Export the build from EDSY or Coriolis as SLEF (or copy a Loadout line from a journal).") from None
    entries = raw if isinstance(raw, list) else [raw]
    builds: List[Build] = []
    for entry in entries:
        data = entry.get("data") if isinstance(entry, dict) and isinstance(entry.get("data"), dict) else entry
        modules = data.get("Modules") if isinstance(data, dict) else None
        if not isinstance(modules, list):
            continue
        if len(modules) > MAX_MODULES:
            raise PlanError(f"A ship has at most {MAX_MODULES} modules; this one lists {len(modules)}.")
        builds.append(Build(_words(data.get("Ship")) or "Ship", str(data.get("ShipName") or "").strip()[:60],
                            tuple(m for m in modules if isinstance(m, dict))))
    if not builds:
        raise PlanError("No ship with modules found in that text. A ship loadout has a \"Modules\" list.")
    return builds


def _level(raw: Any) -> int:
    return raw if isinstance(raw, int) and not isinstance(raw, bool) and 1 <= raw <= MAX_LEVEL else 0


def plan_module(module: Dict[str, Any]) -> Optional[PlannedModule]:
    """What one module takes; None for a module with no engineering (nothing to plan)."""
    engineering = module.get("Engineering")
    if not isinstance(engineering, dict) or not engineering.get("BlueprintName"):
        return None
    slot, item = str(module.get("Slot") or "")[:40], str(module.get("Item") or "")[:80]
    journal_name = str(engineering.get("BlueprintName"))[:60]
    level = _level(engineering.get("Level"))
    quality = float(engineering["Quality"]) if isinstance(engineering.get("Quality"), (int, float)) and not isinstance(engineering.get("Quality"), bool) else 0.0
    kind = module_type(item)
    shown = str(engineering.get("ExperimentalEffect_Localised") or "")[:40]

    def skip(status: str, note: str, blueprint: str = journal_name) -> PlannedModule:
        return PlannedModule(slot, item, kind, blueprint, level, shown, status, note, (), None, quality)

    if engineering.get("EngineerID") == PRE_ENGINEERED_ID:
        return skip(PRE, "Pre-engineered: it comes that way, nothing to craft.")
    if not kind:
        return skip(NOT_COUNTED, "WNTB's table has no module type for this item.")
    name = BLUEPRINT_NAMES.get(journal_name, {}).get(kind)
    if name is None:
        return skip(NOT_COUNTED, f"WNTB's table has no {journal_name} blueprint for a {kind}.")
    if not level:
        return skip(NOT_COUNTED, "The engineering level is missing or not 1 to 5.", name)
    grades = tuple(b for b in blueprints.grades_for(kind, name) if 1 <= b.grade <= level)
    if len(grades) < level:
        return PlannedModule(slot, item, kind, name, level, shown, PARTLY if grades else NOT_COUNTED,
                             f"The table has {len(grades)} of the {level} grades of this blueprint.", grades, None, quality)
    special: Optional[blueprints.Blueprint] = None
    note, status = "", COUNTED
    effect = str(engineering.get("ExperimentalEffect") or "")
    if effect:
        wanted = SPECIAL_NAMES.get(effect, ())
        special = next((b for n in wanted for b in blueprints.grades_for(kind, n) if b.grade == 0), None)
        if special is None:
            status, note = PARTLY, "The experimental effect is not in the table, so only the grades are counted."
        else:
            shown = special.name
    return PlannedModule(slot, item, kind, name, level, shown, status, note, grades, special, quality)


@dataclass(frozen=True)
class Plan:
    build: Build
    modules: Tuple[PlannedModule, ...]

    def entries(self, rolls: int = 1) -> List[Tuple[str, int]]:
        """(blueprint id, crafts) for the whole build, the same blueprint from different modules added together, in the order first met.
        Each grade takes `rolls` crafts and an experimental effect one. Raises PlanError for rolls outside 1 to MAX_ROLLS."""
        if isinstance(rolls, bool) or not isinstance(rolls, int) or not 1 <= rolls <= MAX_ROLLS:
            raise PlanError(f"Rolls per grade must be a whole number from 1 to {MAX_ROLLS}.")
        total: Dict[str, int] = {}
        for module in self.modules:
            for blueprint in module.grades:
                total[blueprint.id] = total.get(blueprint.id, 0) + rolls
            if module.special is not None:
                total[module.special.id] = total.get(module.special.id, 0) + 1
        return list(total.items())

    def counted(self) -> int:
        """How many modules contribute something to the plan."""
        return sum(1 for m in self.modules if m.grades or m.special is not None)

    def summary(self, rolls: int = 1) -> str:
        entries = self.entries(rolls)
        crafts = sum(c for _id, c in entries)
        skipped = len(self.modules) - self.counted()
        text = f"{len(self.modules)} engineered module{'s' if len(self.modules) != 1 else ''}: {len(entries)} blueprint{'s' if len(entries) != 1 else ''}, {crafts} craft{'s' if crafts != 1 else ''}"
        return text + (f"; {skipped} not counted" if skipped else "")


def plan(build: Build) -> Plan:
    return Plan(build, tuple(p for p in (plan_module(m) for m in build.modules) if p is not None))
